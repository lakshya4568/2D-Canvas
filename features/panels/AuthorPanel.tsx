function ParameterRow({ parameter }: { parameter: SketchParameter }) {
  const { setParameterValue, updateParameter, renameParameter, dependentsFor, sketch, createDerivedParameter } = useUpce();
  const [open, setOpen] = React.useState(false);
  const [draft, setDraft] = React.useState(String(parameter.value));
  const [nameDraft, setNameDraft] = React.useState(parameter.name);
  const [editingName, setEditingName] = React.useState(false);

  React.useEffect(() => setDraft(String(parameter.value)), [parameter.value]);

  const dependents = dependentsFor(parameter.name);
  const drives = parameter.boundConstraints
    .map((id) => sketch.constraints.find((c) => c.id === id)?.label)
    .filter(Boolean) as string[];

  return (
    <div className="border-t border-(--rule) first:border-t-0">
      <div className="flex items-center gap-2 px-2.5 h-[32px]">
        <span
          className={`text-[9px] px-1 rounded-sm font-semibold tracking-wide ${ROLE_TONE[parameter.role]}`}
        >
          {parameter.role.slice(0, 3)}
        </span>
        {editingName ? (
          <input
            autoFocus
            value={nameDraft}
            onChange={(e) => setNameDraft(e.target.value)}
            onBlur={() => {
              setEditingName(false);
              renameParameter(parameter.name, nameDraft);
            }}
            onKeyDown={(e) => e.key === "Enter" && e.currentTarget.blur()}
            className="flex-1 min-w-0 h-[20px] px-1 text-[11.5px] bg-(--ink-sunken) border border-(--pen) rounded-[3px] outline-none text-(--fg-primary)"
          />
        ) : (
          <button
            onDoubleClick={() => setEditingName(true)}
            onClick={() => setOpen((v) => !v)}
            title="Double-click to rename"
            className="flex-1 min-w-0 text-left text-[11.5px] text-(--fg-secondary) truncate cursor-pointer hover:text-(--fg-primary)"
          >
            {parameter.name}
          </button>
        )}
        {parameter.role === "DRIVING" ? (
          <input
            value={draft}
            inputMode="decimal"
            onChange={(e) => setDraft(e.target.value)}
            onBlur={() => {
              const v = Number(draft);
              if (Number.isFinite(v) && v !== parameter.value) setParameterValue(parameter.name, v);
              else setDraft(String(parameter.value));
            }}
            onKeyDown={(e) => {
              if (e.key === "Enter") (e.target as HTMLInputElement).blur();
              if (e.key === "Escape") {
                setDraft(String(parameter.value));
                e.currentTarget.blur();
              }
            }}
            className="num w-[64px] h-[22px] px-1.5 text-right text-[11.5px] bg-(--ink-raised) border border-(--rule) rounded-[3px] outline-none focus:border-(--pen) text-(--fg-primary)"
          />
        ) : (
          <span className="num text-[11.5px] text-(--fg-muted) inline-flex items-center gap-1">
            <Lock className="w-[9px] h-[9px]" strokeWidth={2.2} />
            {parameter.value.toFixed(1)}
          </span>
        )}
        <span className="text-[9.5px] text-(--fg-muted) w-[24px]">{parameter.unit}</span>
      </div>

      {open && (
        <div className="px-2.5 pb-2.5 pt-0.5 flex flex-col gap-1.5 text-[10.5px] leading-[1.55]">
          <p className="text-(--fg-secondary)">
            <span className="text-(--fg-muted)">Origin · </span>
            {ORIGIN_LABEL[parameter.provenance.origin] ?? parameter.provenance.origin}
          </p>
          <p className="text-(--fg-muted)">{parameter.provenance.detail}</p>
          
          <div className="flex items-center gap-1.5 pt-1">
            <label className="text-(--fg-muted) shrink-0">Formula</label>
            <input
              key={parameter.expr ?? ""}
              defaultValue={parameter.expr ?? ""}
              placeholder="e.g. CellCount * CellPitch + 30"
              onKeyDown={(e) => {
                if (e.key === "Enter") (e.target as HTMLInputElement).blur();
              }}
              onBlur={(e) => {
                const expr = e.target.value.trim();
                if (expr && expr !== parameter.expr) {
                  createDerivedParameter(parameter.name, expr);
                } else if (!expr && parameter.expr) {
                  updateParameter(parameter.name, { role: "DRIVING", expr: undefined, dependencies: [] });
                }
              }}
              className="num flex-1 h-[22px] px-1.5 text-[10.5px] rounded-[3px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
            />
          </div>

          {drives.length > 0 && (
            <div>
              <p className="text-(--fg-secondary)">Changing it moves:</p>
              <ul className="list-none pl-2">
                {drives.map((d, i) => (
                  <li key={i} className="text-(--fg-muted)">
                    · {d}
                  </li>
                ))}
              </ul>
            </div>
          )}
          {dependents.length > 0 && (
            <p className="text-(--fg-muted)">Other values that follow it: {dependents.join(", ")}</p>
          )}
          <div className="flex items-center gap-2 pt-1">
            <label className="text-(--fg-muted)">Range</label>
            <input
              defaultValue={parameter.min ?? ""}
              placeholder="min"
              onBlur={(e) =>
                updateParameter(parameter.name, {
                  min: e.target.value === "" ? undefined : Number(e.target.value),
                })
              }
              className="num w-[52px] h-[20px] px-1 text-right text-[10.5px] rounded-[3px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen)"
            />
            <input
              defaultValue={parameter.max ?? ""}
              placeholder="max"
              onBlur={(e) =>
                updateParameter(parameter.name, {
                  max: e.target.value === "" ? undefined : Number(e.target.value),
                })
              }
              className="num w-[52px] h-[20px] px-1 text-right text-[10.5px] rounded-[3px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen)"
            />
            <label className="ml-auto inline-flex items-center gap-1 cursor-pointer text-(--fg-muted)">
              <input
                type="checkbox"
                checked={parameter.published}
                onChange={(e) => updateParameter(parameter.name, { published: e.target.checked })}
              />
              show to users
            </label>
          </div>
        </div>
      )}
    </div>
  );
}

function ConstraintRow({ id }: { id: string }) {
  const { sketch, deleteConstraint, toggleConstraint } = useUpce();
  const c = sketch.constraints.find((x) => x.id === id);
  const [open, setOpen] = React.useState(false);
  if (!c) return null;
  const isFact = c.strength === "fact";
  const suppressed = c.state === "suppressed";

  return (
    <div className="border-t border-(--rule) first:border-t-0">
      <div className="flex items-center gap-1.5 px-2.5 min-h-[28px] py-1">
        <button
          onClick={() => setOpen((v) => !v)}
          className={`flex-1 min-w-0 text-left text-[11px] leading-snug cursor-pointer ${
            suppressed ? "text-(--fg-muted) line-through" : "text-(--fg-secondary) hover:text-(--fg-primary)"
          }`}
        >
          {c.label}
          {c.paramRef && <span className="text-(--pen)"> = {c.paramRef}</span>}
        </button>
        <button
          onClick={() => toggleConstraint(c.id)}
          title={suppressed ? "Switch back on" : "Switch off temporarily"}
          className="shrink-0 w-[20px] h-[20px] grid place-items-center rounded text-(--fg-muted) hover:text-(--fg-primary) cursor-pointer disabled:opacity-30"
          disabled={isFact}
        >
          {suppressed ? <EyeOff className="w-[11px] h-[11px]" /> : <Eye className="w-[11px] h-[11px]" />}
        </button>
        <button
          onClick={() => deleteConstraint(c.id)}
          title={isFact ? "Part of the shape — cannot be removed here" : "Remove"}
          disabled={isFact}
          className="shrink-0 w-[20px] h-[20px] grid place-items-center rounded text-(--fg-muted) hover:text-(--crit) cursor-pointer disabled:opacity-30"
        >
          <Trash2 className="w-[11px] h-[11px]" />
        </button>
      </div>
      {open && (
        <p className="px-2.5 pb-2 text-[10.5px] leading-[1.55] text-(--fg-muted)">
          <span className="text-(--fg-secondary)">
            {ORIGIN_LABEL[c.provenance.origin] ?? c.provenance.origin} ·{" "}
          </span>
          {c.provenance.detail}
          {c.provenance.evidence?.length ? ` (${c.provenance.evidence.join("; ")})` : ""}
        </p>
      )}
    </div>
  );
}

