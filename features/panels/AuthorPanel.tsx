/**
 * Step 4b - relationships the drawing gives no evidence for.
 *
 * Everything above this point is the system proposing and the author choosing.
 * This is the author asserting: these two things are related because I say so.
 * It is the only place in the panel where intent comes from nowhere but the
 * engineer's head, which is exactly §20 of the brief - the normal workflow must
 * not need it, and an author who wants it must have it.
 *
 * Two halves, because a relationship needs both:
 *
 *   MEASURE  select geometry, name what it measures. Until a span has a name
 *            there is nothing an expression can refer to, and the assistant only
 *            offers to name one when naming it removes freedom - so a value you
 *            want purely in order to REFER to it was unreachable. "Report only"
 *            covers that: it records the number without holding the geometry, so
 *            it can never conflict with anything.
 *
 *   LINK     pick a named value and write what it follows. The constraint that
 *            reads it does not change, so the geometry goes on obeying the same
 *            rule; only the source of the number moves. That is why this works
 *            between shapes that share no constraint at all - the link lives in
 *            the scalar graph, and the geometric graph never learns of it (§9).
 */

/**
 * Relationships between two things the drawing says nothing about.
 *
 * Notebook pages 4-6 and 9, in one place. The assistant above can only propose
 * what it can SEE — two edges already parallel, a profile already nested inside
 * another. These are the opposite case: two lines or two shapes that share
 * nothing, tied together because the engineering says so and for no other
 * reason. That is why they are asserted here rather than offered there.
 *
 * Both halves work off the canvas selection, because pointing at the geometry is
 * how a draftsman says which things they mean.
 */
/** One of the two ways to assert a relationship between two pieces of geometry. */
function AssertRelationSection({ pane }: { pane: "edge" | "centre" }) {
  const upce = useUpce();
  const { state } = useDrawing();
  const {
    edgesFor, loopsFor, relationOptionsFor, relateTwoLines, relateTwoCentres,
    shapeRisk, shapeRiskFor, holdShapesOf, dismissShapeRisk,
  } = upce;

  const selection = React.useMemo(
    () => (state.selectedIds.length > 0 ? state.selectedIds : state.selectedId ? [state.selectedId] : []),
    [state.selectedIds, state.selectedId]
  );

  const edges = React.useMemo(() => (selection.length ? edgesFor(selection) : []), [selection, edgesFor]);
  const loops = React.useMemo(() => (selection.length ? loopsFor(selection) : []), [selection, loopsFor]);

  const [edgeA, setEdgeA] = React.useState("");
  const [edgeB, setEdgeB] = React.useState("");
  const [kind, setKind] = React.useState<LineRelationKind>("normal_offset");

  const options = React.useMemo(
    () => (edgeA && edgeB && edgeA !== edgeB ? relationOptionsFor(edgeA, edgeB) : []),
    [edgeA, edgeB, relationOptionsFor]
  );
  const riskNow = React.useMemo(
    () => (selection.length ? shapeRiskFor(selection) : null),
    [selection, shapeRiskFor]
  );
  const chosen = options.find((o) => o.kind === kind);

  return (
    <>

      {/* The rule was created and something it touches can still change shape. */}
      {shapeRisk && (
        <div className="rounded-[6px] border border-(--warn) bg-(--warn-soft) px-2.5 py-2 flex flex-col gap-1.5">
          <p className="text-[10.5px] leading-[1.5] text-(--fg-primary)">{shapeRisk.message}</p>
          <div className="flex items-center gap-1.5">
            <Button onClick={() => holdShapesOf(shapeRisk.shapeIds)} icon={Lock} tone="primary">
              Hold their shape
            </Button>
            <Button onClick={dismissShapeRisk} tone="quiet">
              Leave them free
            </Button>
          </div>
        </div>
      )}

      {/* Before the rule is made, so it can be prevented rather than repaired. */}
      {!shapeRisk && selection.length > 0 && riskNow && (
        <div className="rounded-[6px] border border-dashed border-(--rule) px-2.5 py-2 flex flex-col gap-1.5">
          <p className="text-[10.5px] leading-[1.5] text-(--fg-muted)">
            {riskNow} A rule that moves {selection.length === 1 ? "it" : "them"} may squash{" "}
            {selection.length === 1 ? "it" : "them"} instead — deforming a loose outline costs the
            solver less than carrying it across the sheet.
          </p>
          <Button onClick={() => holdShapesOf(selection)} icon={Lock}>
            Hold their shape first
          </Button>
        </div>
      )}

      {pane === "edge" && (
      <div className="rounded-[6px] border border-(--rule) overflow-hidden">
        <div className="px-2.5 h-[26px] flex items-center gap-1.5 bg-(--ink-raised) border-b border-(--rule)">
          <GitCompare className="w-[12px] h-[12px] text-(--fg-muted)" strokeWidth={2.1} />
          <span className="text-[11px] text-(--fg-secondary)">Hold one edge relative to another</span>
        </div>
        {edges.length < 2 ? (
          <p className="px-2.5 py-2 text-[10.5px] text-(--fg-muted)">
            Select geometry with at least two edges between it.
          </p>
        ) : (
          <div className="px-2.5 py-2 flex flex-col gap-1.5">
            <select
              value={edgeA}
              onChange={(e) => setEdgeA(e.target.value)}
              className="h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
            >
              <option value="">Reference edge…</option>
              {edges.map((e) => (
                <option key={e.segmentId} value={e.segmentId}>{e.label}</option>
              ))}
            </select>
            <select
              value={edgeB}
              onChange={(e) => setEdgeB(e.target.value)}
              className="h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
            >
              <option value="">Edge that follows it…</option>
              {edges.filter((e) => e.segmentId !== edgeA).map((e) => (
                <option key={e.segmentId} value={e.segmentId}>{e.label}</option>
              ))}
            </select>

            {options.length > 0 && (
              <div className="flex flex-col gap-1">
                {options.map((o) => (
                  <button
                    key={o.kind}
                    onClick={() => setKind(o.kind)}
                    className={`text-left px-2 py-1.5 rounded-[5px] border text-[10.5px] leading-[1.45] cursor-pointer ${
                      kind === o.kind
                        ? "border-(--pen) bg-(--ink-raised) text-(--fg-primary)"
                        : "border-(--rule) text-(--fg-muted) hover:text-(--fg-primary)"
                    }`}
                  >
                    <span className="block text-(--fg-primary)">{o.label}</span>
                    <span className="num opacity-70">measures {o.measured.toFixed(1)} mm now</span>
                  </button>
                ))}
              </div>
            )}
            {chosen && <p className="text-[10px] leading-[1.5] text-(--fg-muted)">{chosen.rationale}</p>}

            <Button
              onClick={() => {
                relateTwoLines(edgeA, edgeB, kind);
                setEdgeA("");
                setEdgeB("");
              }}
              disabled={!edgeA || !edgeB || edgeA === edgeB}
              icon={GitCompare}
              tone="primary"
            >
              Hold this relationship
            </Button>
          </div>
        )}
      </div>

      )}

      {pane === "centre" && (
      <div className="rounded-[6px] border border-(--rule) overflow-hidden">
        <div className="px-2.5 h-[26px] flex items-center gap-1.5 bg-(--ink-raised) border-b border-(--rule)">
          <Crosshair className="w-[12px] h-[12px] text-(--fg-muted)" strokeWidth={2.1} />
          <span className="text-[11px] text-(--fg-secondary)">Drive the gap between two centres</span>
        </div>
        {loops.length < 2 ? (
          <p className="px-2.5 py-2 text-[10.5px] text-(--fg-muted)">
            Select two closed shapes. Works on rectangles, circles and anything drawn from
            lines — the centre comes from the boundary, not from the shape&apos;s type.
          </p>
        ) : (
          <div className="px-2.5 py-2 flex flex-col gap-1.5">
            <p className="text-[10.5px] leading-[1.5] text-(--fg-muted)">
              Ties <span className="text-(--fg-primary)">{loops[0].label}</span> to{" "}
              <span className="text-(--fg-primary)">{loops[1].label}</span>. Lowering the value
              brings both in; raising it pushes both out.
            </p>
            <Button
              onClick={() => relateTwoCentres(loops[0].loop, loops[1].loop, loops[0].label, loops[1].label)}
              icon={Crosshair}
              tone="primary"
            >
              Name the centre-to-centre distance
            </Button>
          </div>
        )}
      </div>
      )}
    </>
  );
}

/** One of the two ways to turn a measurement into a named, driven value. */
function RelationshipSection({ pane }: { pane: "measure" | "formula" }) {
  const upce = useUpce();
  const { state } = useDrawing();
  const { sketch, measurablesFor, nameMeasurementAs, linkValue, unlinkValue } = upce;

  const selection = React.useMemo(
    () => (state.selectedIds.length > 0 ? state.selectedIds : state.selectedId ? [state.selectedId] : []),
    [state.selectedIds, state.selectedId]
  );
  const measurables = React.useMemo(
    () => (selection.length > 0 ? measurablesFor(selection) : []),
    [selection, measurablesFor]
  );

  const [chosen, setChosen] = React.useState<string>("");
  const [measureName, setMeasureName] = React.useState("");
  const [mode, setMode] = React.useState<"driving" | "reference">("driving");
  const [target, setTarget] = React.useState<string>("");
  const [expr, setExpr] = React.useState("");

  const active: Measurable | undefined =
    measurables.find((m) => m.id === chosen) ?? measurables[0];

  React.useEffect(() => {
    if (active && !measureName) setMeasureName(active.suggestedName);
  }, [active, measureName]);

  const parameters = Object.values(sketch.parameters);
  const linkable = parameters.filter((p) => p.role === "DRIVING" || p.role === "DERIVED");
  const current = target ? sketch.parameters[target] : undefined;

  // Evaluate what the author has typed against the real parameter values, so a
  // typo shows up here rather than as a refused edit after they press the button.
  const preview = React.useMemo(() => {
    if (!expr.trim() || !target) return null;
    const names: string[] = expr.match(/[A-Za-z_][A-Za-z0-9_]*/g) ?? [];
    const builtins: string[] = ["max", "min", "abs", "round", "ceil", "floor", "sqrt"];
    const unknown = names.filter((n) => !sketch.parameters[n] && !builtins.includes(n));
    if (unknown.length > 0) return { ok: false as const, text: `No value called ${unknown[0]}.` };
    if (names.includes(target)) return { ok: false as const, text: `${target} cannot be written in terms of itself.` };
    return { ok: true as const, text: `${target} stops being typed and follows this instead.` };
  }, [expr, target, sketch.parameters]);

  return (
    <>
      {pane === "measure" && (
      <div className="rounded-[6px] border border-(--rule) overflow-hidden">
        <div className="px-2.5 h-[26px] flex items-center gap-1.5 bg-(--ink-raised) border-b border-(--rule)">
          <Ruler className="w-[12px] h-[12px] text-(--fg-muted)" strokeWidth={2.1} />
          <span className="text-[11px] text-(--fg-secondary)">Measure and name</span>
        </div>
        {selection.length === 0 ? (
          <p className="px-2.5 py-2 text-[10.5px] text-(--fg-muted)">
            Select geometry on the canvas. Select two things to measure the gap between them.
          </p>
        ) : measurables.length === 0 ? (
          <p className="px-2.5 py-2 text-[10.5px] text-(--fg-muted)">
            Nothing measurable in that selection — it has no extent the kernel can lower.
          </p>
        ) : (
          <div className="px-2.5 py-2 flex flex-col gap-1.5">
            <select
              value={active?.id ?? ""}
              onChange={(e) => {
                setChosen(e.target.value);
                const next = measurables.find((m) => m.id === e.target.value);
                setMeasureName(next?.suggestedName ?? "");
              }}
              className="h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
            >
              {measurables.map((m) => (
                <option key={m.id} value={m.id}>
                  {m.label} — {m.value.toFixed(1)} mm
                </option>
              ))}
            </select>
            <div className="flex items-center gap-1.5">
              <input
                value={measureName}
                onChange={(e) => setMeasureName(e.target.value)}
                placeholder="Name"
                className="flex-1 min-w-0 h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
              />
              <select
                value={mode}
                onChange={(e) => setMode(e.target.value as "driving" | "reference")}
                title="A driving value holds the geometry to it. A report-only value records the number and holds nothing."
                className="h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
              >
                <option value="driving">drives it</option>
                <option value="reference">reports only</option>
              </select>
            </div>
            <Button
              onClick={() => {
                if (!active) return;
                nameMeasurementAs(active, measureName || active.suggestedName, mode);
                setMeasureName("");
              }}
              disabled={!active}
              icon={Ruler}
            >
              Name this measurement
            </Button>
          </div>
        )}
      </div>

      )}

      {pane === "formula" && (
      <div className="rounded-[6px] border border-(--rule) overflow-hidden">
        <div className="px-2.5 h-[26px] flex items-center gap-1.5 bg-(--ink-raised) border-b border-(--rule)">
          <Link2 className="w-[12px] h-[12px] text-(--fg-muted)" strokeWidth={2.1} />
          <span className="text-[11px] text-(--fg-secondary)">Make one value follow others</span>
        </div>
        {linkable.length === 0 ? (
          <p className="px-2.5 py-2 text-[10.5px] text-(--fg-muted)">
            No named values yet. Measure something above, or answer a design question.
          </p>
        ) : (
          <div className="px-2.5 py-2 flex flex-col gap-1.5">
            <div className="flex items-center gap-1.5">
              <select
                value={target}
                onChange={(e) => {
                  setTarget(e.target.value);
                  setExpr(sketch.parameters[e.target.value]?.expr ?? "");
                }}
                className="w-[112px] h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
              >
                <option value="">Which value…</option>
                {linkable.map((p) => (
                  <option key={p.name} value={p.name}>
                    {p.name}
                  </option>
                ))}
              </select>
              <span className="text-(--fg-muted) text-[11px]">=</span>
              <input
                value={expr}
                onChange={(e) => setExpr(e.target.value)}
                placeholder="OtherWidth - 2 * WallThickness"
                className="num flex-1 min-w-0 h-[24px] px-1.5 text-[11px] rounded-[4px] bg-(--ink-raised) border border-(--rule) outline-none focus:border-(--pen) text-(--fg-primary)"
              />
            </div>

            {/* Operands, so nobody has to remember a name or its spelling. */}
            <div className="flex flex-wrap gap-1">
              {parameters
                .filter((p) => p.name !== target)
                .map((p) => (
                  <button
                    key={p.name}
                    onClick={() => setExpr((e) => (e ? `${e} ${p.name}` : p.name))}
                    title={`${p.role} · ${p.value.toFixed(2)} ${p.unit}`}
                    className="px-1.5 h-[20px] rounded-[4px] text-[10px] border border-(--rule) text-(--fg-muted) hover:text-(--fg-primary) hover:border-(--rule-strong) cursor-pointer"
                  >
                    {p.name}
                    <span className="num ml-1 opacity-60">{p.value.toFixed(0)}</span>
                  </button>
                ))}
            </div>

            {preview && (
              <p className={`text-[10px] ${preview.ok ? "text-(--fg-muted)" : "text-(--danger)"}`}>
                {preview.text}
              </p>
            )}

            <div className="flex items-center gap-1.5">
              <Button
                onClick={() => {
                  linkValue(target, expr);
                  setExpr("");
                  setTarget("");
                }}
                disabled={!target || !expr.trim() || preview?.ok === false}
                icon={Link2}
                tone="primary"
              >
                Link it
              </Button>
              {current?.role === "DERIVED" && (
                <Button onClick={() => unlinkValue(current.name)} icon={Link2Off} tone="quiet">
                  Take back manual control
                </Button>
              )}
            </div>
          </div>
        )}
      </div>
      )}
    </>
  );
}

/**
 * Every way of relating two things, in one place, choosing between them.
 *
 * These were four separate boxes stacked down the column, each with its own
 * heading and its own pair of dropdowns, all open at once. They are alternatives
 * — you are doing exactly one of them — so a control that says so takes a
 * quarter of the room and asks one question instead of four.
 */
/**
 * The remaining freedoms, a few at a time.
 *
 * An under-defined drawing can have a dozen of these, and printing all twelve
 * turns the most useful panel in the app into a wall. The first few are the ones
 * worth acting on — the list is ordered by how simple the movement is — and the
 * rest are one click away for anyone who wants them.
 */
function FreedomList({ motions }: { motions: { description: string }[] }) {
  const [all, setAll] = React.useState(false);
  const SHOWN = 4;
  const shown = all ? motions : motions.slice(0, SHOWN);
  const hidden = motions.length - shown.length;

  return (
    <div className="px-2.5 py-2 flex flex-col gap-1">
      <ul className="flex flex-col gap-1">
        {shown.map((m, i) => (
          <li key={i} className="text-[10.5px] leading-[1.5] text-(--fg-secondary)">
            · {m.description}
          </li>
        ))}
      </ul>
      {hidden > 0 && (
        <button
          onClick={() => setAll(true)}
          className="self-start text-[10px] text-(--pen) hover:underline cursor-pointer"
        >
          {hidden} more
        </button>
      )}
      {all && motions.length > SHOWN && (
        <button
          onClick={() => setAll(false)}
          className="self-start text-[10px] text-(--fg-muted) hover:text-(--fg-primary) cursor-pointer"
        >
          Show fewer
        </button>
      )}
    </div>
  );
}

function RelationshipsGroup() {
  const [mode, setMode] = React.useState<"measure" | "formula" | "edge" | "centre">("measure");
  const { sketch } = useUpce();
  const derived = Object.values(sketch.parameters).filter((p) => p.role === "DERIVED").length;

  const blurb: Record<typeof mode, string> = {
    measure: "Measure something and give it a name, so it can be typed and published.",
    formula: "Make one named value follow others, with a formula you write.",
    edge: "Hold one edge against another. Move the first and the second comes with it.",
    centre: "Drive two closed shapes together or apart by the distance between their centres.",
  };

  return (
    <Group id="author.relationships" title="Relationships" count={derived > 0 ? derived : undefined}>
      <Segmented
        value={mode}
        onChange={setMode}
        options={[
          { value: "measure", label: "Measure", title: "Measure something and name it" },
          { value: "formula", label: "Formula", title: "Make one value follow others" },
          { value: "edge", label: "Edge", title: "Hold one edge relative to another" },
          { value: "centre", label: "Centre", title: "Drive the gap between two centres" },
        ]}
      />
      <p className="text-[10.5px] leading-[1.5] text-(--fg-muted)">{blurb[mode]}</p>

      {(mode === "measure" || mode === "formula") && <RelationshipSection pane={mode} />}
      {(mode === "edge" || mode === "centre") && <AssertRelationSection pane={mode} />}
    </Group>
  );
}

