/**
 * The AUTHOR dock — the draftsman's parametric authoring workflow.
 *
 * The panel is ordered the way the work is actually done, not the way the
 * architecture is layered:
 *
 *     analyse  ->  review what was found  ->  see what is still free
 *              ->  answer the design questions  ->  name the values
 *              ->  group and repeat  ->  check  ->  publish
 *
 * Two rules from the brief are visible in every section below:
 *
 *   §3.3  a candidate says what was detected, from which measurements, how far
 *         off it is, and what accepting it will preserve. Nothing is applied
 *         until the author presses Accept.
 *
 *   §13   the author must be able to tell apart a measured fact, an accepted
 *         inference, a driving value, a derived value and a system default —
 *         so every parameter row carries its origin, and every derived value
 *         can be asked "why do you exist?".
 */

