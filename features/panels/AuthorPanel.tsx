function NoticeBar() {
  const { notice, dismissNotice } = useUpce();
  if (!notice) return null;
  const tone =
    notice.kind === "error"
      ? "border-(--crit) bg-(--crit-soft) text-(--crit)"
      : notice.kind === "warn"
        ? "border-(--warn) bg-(--warn-soft) text-(--warn)"
        : notice.kind === "ok"
          ? "border-(--ok) bg-(--ok-soft) text-(--ok)"
          : "border-(--rule) bg-(--ink-raised) text-(--fg-secondary)";
  const Icon =
    notice.kind === "error" ? CircleX : notice.kind === "warn" ? TriangleAlert : notice.kind === "ok" ? CircleCheck : Info;
  return (
    <div className={`rounded-[6px] border px-2.5 py-2 flex items-start gap-2 ${tone}`}>
      <Icon className="w-[13px] h-[13px] mt-[1px] shrink-0" strokeWidth={2.1} />
      <p className="text-[11px] leading-[1.5] flex-1">{notice.text}</p>
      <button onClick={dismissNotice} className="shrink-0 cursor-pointer opacity-60 hover:opacity-100">
        <X className="w-[11px] h-[11px]" strokeWidth={2.4} />
      </button>
    </div>
  );
}

