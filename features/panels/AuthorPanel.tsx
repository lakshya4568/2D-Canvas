function Button({
  onClick,
  children,
  icon: Icon,
  tone = "default",
  disabled,
  title,
}: {
  onClick: () => void;
  children: React.ReactNode;
  icon?: typeof Scan;
  tone?: "default" | "primary" | "quiet";
  disabled?: boolean;
  title?: string;
}) {
  const cls =
    tone === "primary"
      ? "bg-(--pen) text-(--ink-app) hover:opacity-90"
      : tone === "quiet"
        ? "text-(--fg-muted) hover:text-(--fg-primary) hover:bg-(--ink-raised)"
        : "border border-(--rule) text-(--fg-secondary) hover:text-(--fg-primary) hover:border-(--rule-strong)";
  return (
    <button
      onClick={onClick}
      disabled={disabled}
      title={title}
      className={`h-[26px] px-2.5 rounded-[5px] text-[11.5px] font-medium inline-flex items-center gap-1.5 transition-colors duration-100 cursor-pointer disabled:opacity-40 disabled:cursor-not-allowed ${cls}`}
    >
      {Icon && <Icon className="w-[12px] h-[12px]" strokeWidth={2.1} />}
      {children}
    </button>
  );
}

